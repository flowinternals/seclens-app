export const DEFAULT_OPENAI_MODEL_ID = 'gpt-4o-mini'

/** Chat Completions request-parameter families (model API contracts). */
export const OPENAI_CHAT_COMPLETION_REQUEST_FAMILY = Object.freeze({
  GPT5_REASONING: 'gpt5_reasoning',
  O_SERIES_REASONING: 'o_series_reasoning',
  LEGACY_CHAT: 'legacy_chat',
})

export function getOpenAIModelById(modelId) {
  const id = String(modelId || '').trim()
  return OPENAI_MODEL_CATALOG.find((model) => model.id === id) || null
}

export function resolveOpenAIModel(modelId, fallbackId = DEFAULT_OPENAI_MODEL_ID) {
  return (
    getOpenAIModelById(modelId) ||
    getOpenAIModelById(fallbackId) ||
    OPENAI_MODEL_CATALOG[0]
  )
}

/**
 * Classify the Chat Completions parameter contract for a model id.
 * GPT-5 and o-series reasoning models reject `max_tokens` and non-default temperature.
 */
export function classifyOpenAIChatCompletionRequestFamily(modelId) {
  const id = String(modelId || '').trim().toLowerCase()
  if (!id) return OPENAI_CHAT_COMPLETION_REQUEST_FAMILY.LEGACY_CHAT
  if (id.startsWith('gpt-5')) {
    return OPENAI_CHAT_COMPLETION_REQUEST_FAMILY.GPT5_REASONING
  }
  if (/^o[0-9]/.test(id)) {
    return OPENAI_CHAT_COMPLETION_REQUEST_FAMILY.O_SERIES_REASONING
  }
  return OPENAI_CHAT_COMPLETION_REQUEST_FAMILY.LEGACY_CHAT
}

/**
 * @returns {{
 *   family: string,
 *   modelId: string,
 *   outputTokenParam: 'max_completion_tokens' | 'max_tokens',
 *   supportsCustomTemperature: boolean,
 * }}
 */
export function getOpenAIChatCompletionRequestContract(modelId) {
  const resolved = resolveOpenAIModel(modelId)
  const family = classifyOpenAIChatCompletionRequestFamily(resolved.id)
  const usesCompletionTokenBudget =
    family === OPENAI_CHAT_COMPLETION_REQUEST_FAMILY.GPT5_REASONING ||
    family === OPENAI_CHAT_COMPLETION_REQUEST_FAMILY.O_SERIES_REASONING

  return {
    family,
    modelId: resolved.id,
    outputTokenParam: usesCompletionTokenBudget ? 'max_completion_tokens' : 'max_tokens',
    supportsCustomTemperature: !usesCompletionTokenBudget,
  }
}

/**
 * Telemetry-safe summary of the resolved request contract (no prompts/secrets).
 */
export function summarizeOpenAIChatCompletionRequestContract(modelId) {
  const contract = getOpenAIChatCompletionRequestContract(modelId)
  return {
    family: contract.family,
    outputTokenParam: contract.outputTokenParam,
    temperatureMode: contract.supportsCustomTemperature ? 'custom' : 'model_default_only',
  }
}

function hasOwn(obj, key) {
  return Object.prototype.hasOwnProperty.call(obj, key)
}

/**
 * Validate a Chat Completions create payload against the model family contract.
 * Fails locally with an actionable error instead of waiting for a remote 4xx.
 * @returns {ReturnType<typeof getOpenAIChatCompletionRequestContract>}
 */
export function assertOpenAIChatCompletionCreateParams(params) {
  const modelId = params?.model
  if (!modelId || typeof modelId !== 'string') {
    throw new Error('OpenAI chat completion params missing model')
  }

  const contract = getOpenAIChatCompletionRequestContract(modelId)

  if (contract.outputTokenParam === 'max_completion_tokens') {
    if (hasOwn(params, 'max_tokens')) {
      throw new Error(
        `Unsupported OpenAI request contract for model "${contract.modelId}": max_tokens is not supported; use max_completion_tokens (family=${contract.family}).`
      )
    }
    if (!hasOwn(params, 'max_completion_tokens')) {
      throw new Error(
        `Unsupported OpenAI request contract for model "${contract.modelId}": max_completion_tokens is required (family=${contract.family}).`
      )
    }
  } else if (!hasOwn(params, 'max_tokens') && !hasOwn(params, 'max_completion_tokens')) {
    throw new Error(
      `Unsupported OpenAI request contract for model "${contract.modelId}": max_tokens is required (family=${contract.family}).`
    )
  }

  if (!contract.supportsCustomTemperature && hasOwn(params, 'temperature')) {
    const temperature = params.temperature
    if (temperature !== 1 && temperature !== undefined && temperature !== null) {
      throw new Error(
        `Unsupported OpenAI request contract for model "${contract.modelId}": custom temperature is not supported (family=${contract.family}); omit temperature to use the model default.`
      )
    }
  }

  return contract
}

/**
 * Build Chat Completions create params for the resolved model family.
 * GPT-5 / o-series: max_completion_tokens, temperature omitted.
 * Legacy chat models: max_tokens + temperature.
 */
export function buildOpenAIChatCompletionCreateParams({
  model,
  messages,
  maxOutputTokens,
  temperature = 0.1,
} = {}) {
  if (!Array.isArray(messages)) {
    throw new Error('OpenAI chat completion params require a messages array')
  }

  const contract = getOpenAIChatCompletionRequestContract(model)
  const tokens = Number(maxOutputTokens)
  if (!Number.isFinite(tokens) || tokens < 1) {
    throw new Error(
      `Invalid maxOutputTokens for OpenAI chat completion (model=${contract.modelId}): ${maxOutputTokens}`
    )
  }

  const params = {
    model: contract.modelId,
    messages,
    [contract.outputTokenParam]: Math.floor(tokens),
  }

  if (contract.supportsCustomTemperature && temperature !== undefined && temperature !== null) {
    params.temperature = temperature
  }

  assertOpenAIChatCompletionCreateParams(params)
  return params
}

export function estimateOpenAIUsageCostUsd(totalUsage, modelId) {
  const model = resolveOpenAIModel(modelId)
  const promptTokens = typeof totalUsage?.prompt_tokens === 'number' ? totalUsage.prompt_tokens : 0
  const completionTokens =
    typeof totalUsage?.completion_tokens === 'number' ? totalUsage.completion_tokens : 0
  const inputCost = (promptTokens / 1_000_000) * model.inputCostPer1MUsd
  const outputCost = (completionTokens / 1_000_000) * model.outputCostPer1MUsd
  return Number((inputCost + outputCost).toFixed(5))
}

export function formatUsdPerMillionTokens(amount) {
  return `$${Number(amount || 0).toFixed(2)}/1M`
}
